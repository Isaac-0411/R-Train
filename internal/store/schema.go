package store

// sqliteSchema is the initial schema of a SQLite database.
var sqliteSchema = []string{
	`CREATE TABLE IF NOT EXISTS users (
		id            INTEGER PRIMARY KEY AUTOINCREMENT,
		username      TEXT    NOT NULL UNIQUE COLLATE NOCASE,
		display_name  TEXT    NOT NULL DEFAULT '',
		password_hash TEXT    NOT NULL,
		role          TEXT    NOT NULL CHECK (role IN ('admin','user')),
		is_root       INTEGER NOT NULL DEFAULT 0,
		created_at    TEXT    NOT NULL
	)`,
	`CREATE UNIQUE INDEX IF NOT EXISTS idx_users_root ON users(is_root) WHERE is_root = 1`,
	`CREATE TABLE IF NOT EXISTS sessions (
		id         TEXT    PRIMARY KEY,
		user_id    INTEGER REFERENCES users(id) ON DELETE CASCADE,
		csrf_token TEXT    NOT NULL,
		flash      TEXT    NOT NULL DEFAULT '',
		flash_kind TEXT    NOT NULL DEFAULT '',
		created_at TEXT    NOT NULL,
		expires_at TEXT    NOT NULL,
		ip         TEXT    NOT NULL DEFAULT '',
		user_agent TEXT    NOT NULL DEFAULT ''
	)`,
	`CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id)`,
	`CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at)`,
	`CREATE TABLE IF NOT EXISTS lessons (
		id         INTEGER PRIMARY KEY AUTOINCREMENT,
		title      TEXT    NOT NULL,
		summary    TEXT    NOT NULL DEFAULT '',
		passage    TEXT    NOT NULL DEFAULT '',
		position   INTEGER NOT NULL DEFAULT 0,
		published  INTEGER NOT NULL DEFAULT 1,
		created_at TEXT    NOT NULL,
		updated_at TEXT    NOT NULL
	)`,
	`CREATE TABLE IF NOT EXISTS questions (
		id             INTEGER PRIMARY KEY AUTOINCREMENT,
		lesson_id      INTEGER NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
		prompt         TEXT    NOT NULL,
		options        TEXT    NOT NULL DEFAULT '[]',
		correct_option INTEGER NOT NULL DEFAULT 1,
		position       INTEGER NOT NULL DEFAULT 0,
		created_at     TEXT    NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS idx_questions_lesson ON questions(lesson_id, position, id)`,
	`CREATE TABLE IF NOT EXISTS attempts (
		id           INTEGER PRIMARY KEY AUTOINCREMENT,
		user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		lesson_id    INTEGER NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
		score        INTEGER NOT NULL,
		total        INTEGER NOT NULL,
		passed       INTEGER NOT NULL DEFAULT 0,
		submitted_at TEXT    NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS idx_attempts_user ON attempts(user_id, submitted_at DESC)`,
	`CREATE INDEX IF NOT EXISTS idx_attempts_lesson ON attempts(lesson_id)`,
	`CREATE TABLE IF NOT EXISTS attempt_answers (
		id              INTEGER PRIMARY KEY AUTOINCREMENT,
		attempt_id      INTEGER NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
		question_id     INTEGER NOT NULL,
		selected_option TEXT    NOT NULL,
		is_correct      INTEGER NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS idx_attempt_answers_attempt ON attempt_answers(attempt_id)`,
}

// postgresSchema is the same schema expressed for PostgreSQL.
//
// Ids use identity columns and usernames are compared case-insensitively
// through a unique index on lower(username); PostgreSQL has no COLLATE
// NOCASE. Timestamps remain RFC3339 strings because every query already
// treats them as text and the format sorts correctly.
var postgresSchema = []string{
	`CREATE TABLE IF NOT EXISTS users (
		id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		username      TEXT    NOT NULL,
		display_name  TEXT    NOT NULL DEFAULT '',
		password_hash TEXT    NOT NULL,
		role          TEXT    NOT NULL CHECK (role IN ('admin','user')),
		is_root       INTEGER NOT NULL DEFAULT 0,
		created_at    TEXT    NOT NULL
	)`,
	`CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users (lower(username))`,
	`CREATE UNIQUE INDEX IF NOT EXISTS idx_users_root ON users(is_root) WHERE is_root = 1`,
	`CREATE TABLE IF NOT EXISTS sessions (
		id         TEXT   PRIMARY KEY,
		user_id    BIGINT REFERENCES users(id) ON DELETE CASCADE,
		csrf_token TEXT   NOT NULL,
		flash      TEXT   NOT NULL DEFAULT '',
		flash_kind TEXT   NOT NULL DEFAULT '',
		created_at TEXT   NOT NULL,
		expires_at TEXT   NOT NULL,
		ip         TEXT   NOT NULL DEFAULT '',
		user_agent TEXT   NOT NULL DEFAULT ''
	)`,
	`CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id)`,
	`CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at)`,
	`CREATE TABLE IF NOT EXISTS lessons (
		id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		title      TEXT    NOT NULL,
		summary    TEXT    NOT NULL DEFAULT '',
		passage    TEXT    NOT NULL DEFAULT '',
		position   INTEGER NOT NULL DEFAULT 0,
		published  INTEGER NOT NULL DEFAULT 1,
		created_at TEXT    NOT NULL,
		updated_at TEXT    NOT NULL
	)`,
	`CREATE TABLE IF NOT EXISTS questions (
		id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		lesson_id      BIGINT  NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
		prompt         TEXT    NOT NULL,
		options        TEXT    NOT NULL DEFAULT '[]',
		correct_option INTEGER NOT NULL DEFAULT 1,
		position       INTEGER NOT NULL DEFAULT 0,
		created_at     TEXT    NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS idx_questions_lesson ON questions(lesson_id, position, id)`,
	`CREATE TABLE IF NOT EXISTS attempts (
		id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		user_id      BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		lesson_id    BIGINT  NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
		score        INTEGER NOT NULL,
		total        INTEGER NOT NULL,
		passed       INTEGER NOT NULL DEFAULT 0,
		submitted_at TEXT    NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS idx_attempts_user ON attempts(user_id, submitted_at DESC)`,
	`CREATE INDEX IF NOT EXISTS idx_attempts_lesson ON attempts(lesson_id)`,
	`CREATE TABLE IF NOT EXISTS attempt_answers (
		id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		attempt_id      BIGINT  NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
		question_id     BIGINT  NOT NULL,
		selected_option TEXT    NOT NULL,
		is_correct      INTEGER NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS idx_attempt_answers_attempt ON attempt_answers(attempt_id)`,
}
